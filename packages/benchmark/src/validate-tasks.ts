import { readFile, readdir, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join } from 'node:path'

import { loadTasks, validateSuite, type Task, type TaskViolation } from './tasks.js'

const TASKS_DIR = new URL('../tasks/', import.meta.url).pathname
const TWINS = new URL('../.twins/', import.meta.url).pathname

const red = (s: string) => `\x1b[31m${s}\x1b[0m`
const green = (s: string) => `\x1b[32m${s}\x1b[0m`
const dim = (s: string) => `\x1b[2m${s}\x1b[0m`

function renderIndex(byRepo: Map<string, Task[]>): string {
  const lines = [
    '# Task index',
    '',
    'Generated by `pnpm --filter @clarxai/benchmark tasks`. Task text is identical in both',
    'twins; only the repository around it differs.',
    '',
    'Prompts deliberately describe **behaviour, never file locations**. Finding the right file is',
    'the navigation cost under measurement — naming it in the prompt would hand the agent the',
    'thing the experiment is trying to price.',
    '',
    'Tasks were authored against `base`, the repository before adoption, so the author could not',
    'bias them toward a manifest they had not seen. `touches` is recorded for validation only and',
    'is never shown to the agent.',
    '',
  ]
  for (const [repo, tasks] of [...byRepo].sort()) {
    lines.push(`## ${repo}`, '')
    lines.push('| ID | Kind | Difficulty | Check |', '| --- | --- | --- | --- |')
    for (const t of tasks) {
      const check = t.checkCommand ? `\`${t.checkCommand}\`` : `rubric (${t.rubric?.length ?? 0} items)`
      lines.push(`| ${t.id} | ${t.kind.replace('_', ' ')} | ${t.difficulty} | ${check} |`)
    }
    lines.push('')
    for (const t of tasks) {
      lines.push(`### ${t.id} — ${t.kind.replace('_', ' ')}`, '', t.prompt, '',
        `**Contamination:** ${t.contaminationNote}`, '')
    }
  }
  return lines.join('\n') + '\n'
}

async function main(): Promise<void> {
  const repos = existsSync(TASKS_DIR)
    ? (await readdir(TASKS_DIR, { withFileTypes: true })).filter(e => e.isDirectory()).map(e => e.name)
    : []

  const byRepo = new Map<string, Task[]>()
  const allViolations: TaskViolation[] = []

  for (const repo of repos.sort()) {
    const tasks = await loadTasks(join(TASKS_DIR, repo))
    byRepo.set(repo, tasks)

    // Paths are asserted against `base`: identical source in both twins, and the
    // version the tasks were authored against.
    const repoRoot = join(TWINS, repo, 'base')
    if (!existsSync(repoRoot)) {
      console.log(`${dim('skip')}  ${repo} — no checkout; run \`pnpm --filter @clarxai/benchmark twins\` first`)
      continue
    }
    const manifestPath = join(TWINS, repo, 'twin_high', 'clarx-manifest.json')
    const manifestJson = existsSync(manifestPath) ? await readFile(manifestPath, 'utf-8') : null

    const violations = validateSuite(tasks, repoRoot, manifestJson, join(TASKS_DIR, repo, 'checks'))
    allViolations.push(...violations)

    console.log(
      violations.length === 0
        ? `${green('ok')}    ${repo} — ${tasks.length} tasks, no violations`
        : `${red('fail')}  ${repo} — ${tasks.length} tasks, ${violations.length} violation(s)`,
    )
    for (const violation of violations) {
      console.log(`      ${red('✗')} ${violation.taskId} ${dim(violation.rule)}: ${violation.detail}`)
    }
  }

  await writeFile(join(TASKS_DIR, 'TASK_INDEX.md'), renderIndex(byRepo), 'utf-8')
  console.log(`\nTASK_INDEX.md written · ${[...byRepo.values()].flat().length} tasks total`)
  process.exit(allViolations.length > 0 ? 1 : 0)
}

main().catch(err => { console.error(err); process.exit(1) })
